#!/bin/sh
# Regenerate THIRD_PARTY_LICENSES.txt at the repo root.
#
# The file ships in every release tarball and in the npm package. It holds the
# licence texts for everything compiled into csr-engine that is not this
# project's own code: the embedded fonts, the embedded reranker model, the
# statically linked ONNX Runtime and every Rust crate in the release build.
#
# Needs cargo-about (`brew install cargo-about` or `cargo install cargo-about`).
# Run it again after any Cargo.lock change, any new embedded asset, or an ort
# bump (then replace csr-engine/assets/licenses/onnxruntime-<version>/ with the
# LICENSE and ThirdPartyNotices.txt from the matching onnxruntime wheel).
#
#   scripts/third-party-licenses.sh            write the file
#   scripts/third-party-licenses.sh --check    exit 1 if the file is out of date
set -eu

root=$(cd "$(dirname "$0")/.." && pwd)
engine="$root/csr-engine"
out="$root/THIRD_PARTY_LICENSES.txt"
ort_dir="$engine/assets/licenses/onnxruntime-1.28.0"

command -v cargo-about >/dev/null 2>&1 || {
  echo "third-party-licenses: cargo-about is not installed" >&2
  exit 1
}

work=$(mktemp -d "$root/.third-party-licenses.XXXXXX")
trap 'rm -rf "$work"' EXIT

(cd "$engine" && cargo about generate --locked about.hbs -o "$work/crates.txt")

rule() {
  printf '\n################################################################################\n'
  printf '# %s\n' "$1"
  printf '################################################################################\n\n'
}

section() {
  # section <title> <file>
  printf '\n================================================================================\n'
  printf '%s\n' "$1"
  printf -- '--------------------------------------------------------------------------------\n'
  cat "$2"
  printf '\n'
}

{
  cat <<'EOF'
Self-Reflect (csr-engine): third-party licences

csr-engine is MIT licensed (see LICENSE). The csr-engine binary also contains
the third-party works below. Their licence texts follow, in this order:

  1. Fonts embedded for the companion pane pictures
  2. The embedded search reranker model
  3. ONNX Runtime 1.28.0, statically linked
  4. Rust crates compiled into the binary

Not distributed with the binary: the embedding model
(sentence-transformers/all-MiniLM-L6-v2, Apache-2.0) is downloaded from
Hugging Face on first use and stays under its own licence.

This file is generated by scripts/third-party-licenses.sh. Do not edit it by hand.
EOF

  rule "1. Fonts (embedded as subsets)"
  section "Inter (InterVariable, subset): SIL Open Font License 1.1" "$engine/assets/fonts/Inter-OFL.txt"
  section "Source Serif 4 (variable, subset): SIL Open Font License 1.1" "$engine/assets/fonts/SourceSerif4-OFL.md"
  section "JetBrains Mono (Regular, subset): SIL Open Font License 1.1" "$engine/assets/fonts/JetBrainsMono-OFL.txt"
  section "Lucide icons (font subset): ISC License" "$engine/assets/fonts/Lucide-ISC.txt"

  rule "2. Search reranker model (ettin-tuned-run2)"
  section "NOTICE" "$engine/assets/models/ettin-tuned-run2/NOTICE"
  section "cross-encoder/ettin-reranker-32m-v1: Apache License 2.0" "$engine/assets/models/ettin-tuned-run2/LICENSE-Apache-2.0.txt"
  cat <<'EOF'

================================================================================
jhu-clsp/ettin-encoder-32m (base encoder of the reranker): MIT License
--------------------------------------------------------------------------------
The model card at https://huggingface.co/jhu-clsp/ettin-encoder-32m declares
the MIT License and publishes no separate copyright line.

Permission is hereby granted, free of charge, to any person obtaining a copy
of this software and associated documentation files (the "Software"), to deal
in the Software without restriction, including without limitation the rights
to use, copy, modify, merge, publish, distribute, sublicense, and/or sell
copies of the Software, and to permit persons to whom the Software is
furnished to do so, subject to the following conditions:

The above copyright notice and this permission notice shall be included in all
copies or substantial portions of the Software.

THE SOFTWARE IS PROVIDED "AS IS", WITHOUT WARRANTY OF ANY KIND, EXPRESS OR
IMPLIED, INCLUDING BUT NOT LIMITED TO THE WARRANTIES OF MERCHANTABILITY,
FITNESS FOR A PARTICULAR PURPOSE AND NONINFRINGEMENT. IN NO EVENT SHALL THE
AUTHORS OR COPYRIGHT HOLDERS BE LIABLE FOR ANY CLAIM, DAMAGES OR OTHER
LIABILITY, WHETHER IN AN ACTION OF CONTRACT, TORT OR OTHERWISE, ARISING FROM,
OUT OF OR IN CONNECTION WITH THE SOFTWARE OR THE USE OR OTHER DEALINGS IN THE
SOFTWARE.
EOF

  rule "3. ONNX Runtime 1.28.0 (statically linked through the ort crate)"
  section "ONNX Runtime: MIT License" "$ort_dir/LICENSE"
  section "ONNX Runtime: third-party notices" "$ort_dir/ThirdPartyNotices.txt"

  rule "4. Rust crates (generated by cargo-about from csr-engine/Cargo.lock)"
  cat "$work/crates.txt"
} > "$work/THIRD_PARTY_LICENSES.txt"

if [ "${1:-}" = "--check" ]; then
  if cmp -s "$work/THIRD_PARTY_LICENSES.txt" "$out"; then
    echo "THIRD_PARTY_LICENSES.txt is up to date"
  else
    echo "THIRD_PARTY_LICENSES.txt is out of date; run scripts/third-party-licenses.sh" >&2
    exit 1
  fi
else
  mv "$work/THIRD_PARTY_LICENSES.txt" "$out"
  echo "wrote $out ($(wc -c < "$out" | tr -d ' ') bytes)"
fi
